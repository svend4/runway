/** Все строки интерфейса по языкам (каталог приложения; каталоги пакетов — в `EXT_STRINGS`, см. `register_strings`). */
export const STRINGS = Object.freeze({ ru: Object.freeze(RU), en: Object.freeze(EN) });

// ── слияние каталогов пакетов (FP-01): единственная точка, где строки пакетов попадают в словарь ─────────────────────────
// Каждый пакет держит свой каталог `demo/i18n/<пакет>.mjs` (`export default { ru: {…}, en: {…} }`, ключи `<пакет>.<имя>`) и регистрирует его
// через `ext.register_i18n(пакет, каталог)`. Паритет RU/EN, одинаковые плейсхолдеры и отсутствие пересечений с каталогом приложения
// и с другими пакетами проверяются при регистрации; нарушение — исключение, и каталог не принимается целиком.

/** Строки пакетов по языкам (изменяются только `register_strings`). */
const EXT_STRINGS = { ru: {}, en: {} };
/** Зарегистрированные пространства имён пакетов. */
const EXT_NAMESPACES = new Set();

const placeholders_of = (s) => [...String(s).matchAll(/{([A-Za-z0-9_]+)}/g)].map((m) => m[1]).sort().join(',');

/**
 * Принять каталог пакета.
 * @param {string} ns пространство имён пакета: `[a-z][a-z0-9]{1,15}`, не совпадает с пространствами каталога приложения и других пакетов
 * @param {{ru: Object<string, string>, en: Object<string, string>}} catalog все ключи начинаются с `ns.`; наборы ключей RU и EN равны
 * @throws {Error} каталог не принят (ничего не добавлено)
 */
export function register_strings(ns, catalog) {
  if (typeof ns !== 'string' || !/^[a-z][a-z0-9]{1,15}$/.test(ns)) throw new Error('register_strings: пространство имён — [a-z][a-z0-9]{1,15}');
  if (EXT_NAMESPACES.has(ns) || Object.keys(RU).some((k) => k.split('.')[0] === ns)) throw new Error('register_strings: пространство имён занято: ' + ns);
  if (catalog === null || typeof catalog !== 'object' || catalog.ru === null || typeof catalog.ru !== 'object' || catalog.en === null || typeof catalog.en !== 'object') {
    throw new Error('register_strings: нужен каталог { ru, en }');
  }
  const ru = Object.keys(catalog.ru).sort();
  const en = Object.keys(catalog.en).sort();
  if (ru.join(',') !== en.join(',')) throw new Error('register_strings: наборы ключей RU и EN различаются (' + ns + ')');
  for (const k of ru) {
    if (!k.startsWith(ns + '.') || k.length === ns.length + 1) throw new Error('register_strings: ключ вне пространства ' + ns + ': ' + k);
    if (Object.hasOwn(RU, k) || Object.hasOwn(EXT_STRINGS.ru, k)) throw new Error('register_strings: ключ уже есть: ' + k);
    for (const lang of LANGS) {
      const v = catalog[lang][k];
      if (typeof v !== 'string' || v.trim() === '') throw new Error('register_strings: пустая строка ' + k + ' (' + lang + ')');
    }
    if (placeholders_of(catalog.ru[k]) !== placeholders_of(catalog.en[k])) throw new Error('register_strings: плейсхолдеры различаются: ' + k);
  }
  for (const k of ru) { EXT_STRINGS.ru[k] = catalog.ru[k]; EXT_STRINGS.en[k] = catalog.en[k]; }
  EXT_NAMESPACES.add(ns);
}

/** Копия строк зарегистрированных пакетов (для проверок и отладки). */
export function ext_strings() {
  return { ru: { ...EXT_STRINGS.ru }, en: { ...EXT_STRINGS.en } };
}

/**
 * Строка интерфейса с подстановкой `{имя}`; неизвестный ключ — сам ключ (видно сразу), неподставленный плейсхолдер остаётся как есть.
 * @param {'ru'|'en'} lang
 * @param {string} key
 * @param {Object<string, string|number>} [params]
 * @returns {string}
 */
export function t(lang, key, params) {
  const table = STRINGS[lang] ?? STRINGS[DEFAULT_LANG];
  const ext = EXT_STRINGS[lang] ?? EXT_STRINGS[DEFAULT_LANG];
  const raw = Object.hasOwn(table, key) ? table[key] : (Object.hasOwn(ext, key) ? ext[key] : undefined);
  if (raw === undefined) return key;
  if (params === undefined) return raw;
  return raw.replace(/\{([A-Za-z0-9_]+)\}/g, (m, name) => (Object.hasOwn(params, name) ? String(params[name]) : m));
}

/**
 * Подпись данных по идентификатору (`R-RENT`, тег `аренда`, сценарий…): перевод из `DATA_LABELS`, иначе запасное значение.
 * @param {'ru'|'en'} lang
 * @param {string} id
 * @param {string} [fallback] что показать, если перевода нет (по умолчанию сам идентификатор)
 * @returns {string}
 */
export function label_of(lang, id, fallback) {
  const rec = Object.hasOwn(DATA_LABELS, id) ? DATA_LABELS[id] : undefined;
  if (rec !== undefined) return rec[lang] ?? rec.ru;
  return fallback ?? id;
}

/**
 * Плюральная форма слова из `FORMS` (ru: one/few/many, en: one/other); целые числа.
 * @param {'ru'|'en'} lang
 * @param {'day'|'payment'|'row'} word
 * @param {number} n
 * @returns {string}
 */
export function word_form(lang, word, n) {
  const forms = FORMS[word][lang];
  const i = Math.abs(n);
  if (lang === 'ru') {
    const m10 = i % 10;
    const m100 = i % 100;
    if (m10 === 1 && m100 !== 11) return forms[0];
    if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return forms[1];
    return forms[2];
  }
  return i === 1 ? forms[0] : forms[1];
}
