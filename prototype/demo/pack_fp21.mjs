// pack_fp21.mjs — точка входа пакета FP-21 (волна 3а-2): расчёт основных экранов («Обзор», «Купить», «Волны») в Web Worker с откатом на главный поток.
// Что подключается: строки `calc.*` (i18n/calc.mjs) для карточки «Расчёт в фоне» на экране «Настройки» (calc_settings.mjs, флаг `runway-calc-worker/1`), стили busy-состояния
// (css/calc.css) и прогрев воркера при загрузке пакета — пока читается набор данных, модульный воркер успевает запуститься (холодный старт — секунды на слабом телефоне).
// Сама служба (calc_async.mjs) — не пакет: приложение (app.mjs) использует её напрямую, как `build_model`; пакет её только прогревает и даёт строки. Новых слотов и хуков нет.
// Пакет не импортирует app.mjs и ничего не пишет в данные пользователя. Расчёт по введённым данным и правилам, не консультация.

import catalog from './i18n/calc.mjs';
import { calc } from './calc_async.mjs';

/**
 * @param {object} ext реестр расширений (версия для пакета)
 * @param {{calc?: object}} [env] только для тестов: загрузчик реестра второй аргумент не передаёт
 */
export function register(ext, env = {}) {
  const svc = env.calc ?? calc;
  // каталог принимается один раз на процесс: повторная загрузка пакета (тесты, перезапуск реестра) не должна падать
  if (ext.ctx.tr('calc.title') === 'calc.title') ext.register_i18n('calc', catalog);
  ext.ensure_css('css/calc.css');
  svc.warm(); // без Worker (Node, старый браузер) или с выключенным флагом — ничего не делает
  return svc;
}
