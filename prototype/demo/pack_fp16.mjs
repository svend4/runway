// pack_fp16.mjs — точка входа пакета FP-16: подпись курса и его возраста у каждой пересчитанной суммы, тексты плашек курса (REQ-077, REQ-079, REQ-112).
// Подписывается каждая сумма, которую движок пересчитал по курсу: лента, «Почему», карточки волн, ответы ассистента, лист для печати (подписи считает
// `rate_chip.mjs` из `rate_used` / `orig_amount_minor` событий расчёта; рисует их страница, `app.mjs`). Плашка «курс устарел» в шапке называет валюту и возраст,
// сообщение «нет курса» называет пару и ведёт на «Формы данных» → «Курсы и обмен» (`banner_texts.mjs`). Формат чисел и дат пользователя (`ws.number_format`)
// применяется на тех же поверхностях и в ответах ассистента (верификатор принимает его четвёртым параметром), на странице v0, в мастере импорта и «Отменить».
//
// Что регистрируется (новых правок рабочей области пакет не добавляет — он ничего не пишет в данные):
//   - строки `ratechip.*` (RU и EN) — подписи курса, плашка «курс устарел» и сообщение «нет курса»;
//   - стили `css/rate_chip.css` (размер и отступы на токенах темы).
// Подключается реестром (`ext_manifest.mjs`); тексты читает страница через общий каталог строк. Расчёт по введённым данным и правилам, не консультация.

import catalog from './i18n/ratechip.mjs';

/** @param {object} ext реестр расширений (`ext.mjs`, версия для пакета) */
export function register(ext) {
  const ctx = ext.ctx;
  // каталог принимается один раз на процесс: повторная загрузка пакета (тесты, перезапуск реестра) не должна падать
  if (ctx.tr('ratechip.sign') === 'ratechip.sign') ext.register_i18n('ratechip', catalog);
  ext.ensure_css('css/rate_chip.css');
}
