// pack_fp26.mjs — точка входа пакета FP-26 (волна 3а-2): доступность и адаптив — фраза для скринридера, масштаб 200 %, группа «Ещё» на телефоне,
// вторая колонка «Обзора», скелет загрузки, названия ступеней готовности (REQ-049, REQ-167; U21, U22, U23, U35, U40, U41).
// Что делает пакет сам: подключает каталог строк `a11y` (слова для скринридера: названия валют, «минус») и стили `css/layout.css`, а при пересечении границы окна
// телефона (≤ 599 px) просит страницу перерисоваться, чтобы навигация перестроилась (группа «Ещё» включается и выключается вместе с шириной окна).
// Остальное — в самом приложении тонкими вставками без `ext`-хуков: `speech.mjs` (фраза для ползунка графика), `nav_more.mjs` (группа «Ещё»), `skeleton.mjs` (скелет и `aria-busy`),
// две колонки «Обзора» (`view--split`) и название ступени готовности в шапке (`hdr.ready_name_*`). Расчёт и данные не затронуты. Расчёт по введённым данным и правилам, не консультация.
// Подключается реестром (`ext_manifest.mjs`); `app.mjs` пакет по имени не знает.

import catalog from './i18n/a11y.mjs';
import { watch_phone } from './nav_more.mjs';

/**
 * @param {object} ext реестр расширений (`ext.mjs`, версия для пакета)
 * @param {{watch?: (on_change: () => void) => () => void}} [env] только для тестов: подмена подписки на границу окна телефона
 * @returns {{stop: () => void}} снятие подписки (для тестов)
 */
export function register(ext, env = {}) {
  const ctx = ext.ctx;
  // каталог принимается один раз на процесс: повторная загрузка пакета (тесты, перезапуск реестра) не должна падать
  if (ctx.tr('a11y.minus') === 'a11y.minus') ext.register_i18n('a11y', catalog);
  ext.ensure_css('css/layout.css');
  const stop = (env.watch ?? watch_phone)(() => ctx.refresh());
  return { stop };
}
